function define(
  id: string,
  name: string,
  mode: 'light' | 'dark',
  tokens: ThemeDefinition['tokens'],
): ThemeDefinition {
  return {
    id,
    name,
    builtin: true,
    mode,
    monacoTheme: mode === 'dark' ? 'vs-dark' : 'vs',
    preview: {
      bg: tokens['bg-base'] ?? '#000',
      surface: tokens['bg-raised'] ?? '#000',
      fg: tokens['foreground'] ?? '#fff',
      accent: tokens['accent'] ?? '#888',
    },
    tokens,
  };
}

export const BUILTIN_THEMES: readonly ThemeDefinition[] = [
  define('paper-light', 'Paper Light', 'light', PAPER_LIGHT_TOKENS),
  define('paper-dark', 'Paper Dark', 'dark', PAPER_DARK_TOKENS),
  define('midnight', 'Midnight', 'dark', MIDNIGHT_TOKENS),
  define('nord', 'Nord', 'dark', NORD_TOKENS),
  define('solarized-light', 'Solarized Light', 'light', SOLARIZED_LIGHT_TOKENS),
  define('solarized-dark', 'Solarized Dark', 'dark', SOLARIZED_DARK_TOKENS),
];

const BUILTIN_BY_ID = new Map(BUILTIN_THEMES.map((t) => [t.id, t]));

export function getBuiltinTheme(id: string): ThemeDefinition | null {
  return BUILTIN_BY_ID.get(id) ?? null;
}

export function isBuiltinThemeId(id: string): boolean {
  return BUILTIN_BY_ID.has(id);
}

/** 跟随系统时的默认主题 id。 */
export function systemThemeId(prefersDark: boolean): string {
  return prefersDark ? 'paper-dark' : 'paper-light';
}
