fn bundle_single_binary(root: &Path, name: &str) -> Result<(), String> {
    let exe = executable_name(name);
    let bin_dir = root.join("bin");
    fs::create_dir_all(&bin_dir).map_err(|err| format!("create bundled {name} bin dir: {err}"))?;
    let dest = bin_dir.join(&exe);
    if dest.is_file() {
        return ensure_executable(&dest);
    }
    let mut found = None;
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        if dir == bin_dir {
            continue;
        }
        if let Ok(entries) = fs::read_dir(&dir) {
            for entry in entries.filter_map(|e| e.ok()) {
                let path = entry.path();
                if path.is_dir() {
                    stack.push(path);
                } else if path
                    .file_name()
                    .map(|n| n.to_string_lossy() == exe)
                    .unwrap_or(false)
                {
                    found = Some(path);
                    break;
                }
            }
        }
        if found.is_some() {
            break;
        }
    }
    let Some(source) = found else {
        return Err(format!("bundled {name} binary not found after extraction"));
    };
    fs::rename(&source, &dest).map_err(|err| format!("move bundled {name} binary: {err}"))?;
    ensure_executable(&dest)
}

