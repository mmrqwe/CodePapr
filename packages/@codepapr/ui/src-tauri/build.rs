fn dotnet_sdk_download() -> Result<(String, ArchiveKind), String> {
    let os = if target_os() == "macos" {
        "osx"
    } else if target_os() == "linux" {
        "linux"
    } else if target_os() == "windows" {
        "win"
    } else {
        return Err("unsupported target OS for bundled .NET SDK".to_string());
    };

    let arch = if target_arch() == "aarch64" {
        "arm64"
    } else if target_arch() == "x86_64" {
        "x64"
    } else {
        return Err("unsupported target arch for bundled .NET SDK".to_string());
    };

    let ext = if target_os() == "windows" {
        "zip"
    } else {
        "tar.gz"
    };
    let archive_kind = if target_os() == "windows" {
        ArchiveKind::Zip
    } else {
        ArchiveKind::TarGz
    };

    Ok((
        format!("https://dotnetcli.azureedge.net/dotnet/Sdk/{DOTNET_SDK_VERSION}/dotnet-sdk-{DOTNET_SDK_VERSION}-{os}-{arch}.{ext}"),
        archive_kind,
    ))
}

fn ensure_bundled_gopls() -> Result<(), String> {
    let install_root = ui_generated_lsp_resource_dir();
    let gopls_root = install_root.join("gopls");
    let target = gopls_root.join("bin").join(executable_name("gopls"));
    if target.is_file() {
        return ensure_executable(&target);
    }

    if try_copy_from_managed_cache("gopls", &gopls_root)? {
        let copied = gopls_root.join("bin").join(executable_name("gopls"));
        if copied.is_file() {
            return ensure_executable(&copied);
        }
    }

    let go_bin = which_go().unwrap_or_else(|| "go".to_string());
    let gopath = std::env::var("GOPATH").unwrap_or_else(|_| {
        let home = std::env::var("HOME").unwrap_or_default();
        format!("{home}/go")
    });
    let gopath_bin = std::path::Path::new(&gopath)
        .join("bin")
        .join(executable_name("gopls"));
    let _ = fs::create_dir_all(gopls_root.join("bin"));

    if gopath_bin.is_file() {
        let _ = fs::copy(&gopath_bin, &target);
        return ensure_executable(&target);
    }

    match std::process::Command::new(&go_bin)
        .args(["install", "golang.org/x/tools/gopls@latest"])
        .env(
            "GOBIN",
            gopls_root.join("bin").to_string_lossy().to_string(),
        )
        .output()
    {
        Ok(output) if output.status.success() => {
            if target.is_file() {
                return ensure_executable(&target);
            }
        }
        Ok(output) => {
            let stderr = String::from_utf8_lossy(&output.stderr);
            println!("cargo:warning=skipping bundled gopls (go install failed: {stderr})");
        }
        Err(e) => {
            println!("cargo:warning=skipping bundled gopls (go not available: {e})");
        }
    }
    Ok(())
}

