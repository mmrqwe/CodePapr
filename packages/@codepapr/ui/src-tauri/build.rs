fn runtime_identifier() -> &'static str {
    match (
        env::var("CARGO_CFG_TARGET_OS").ok().as_deref(),
        env::var("CARGO_CFG_TARGET_ARCH").ok().as_deref(),
    ) {
        (Some("macos"), Some("aarch64")) => "osx-arm64",
        (Some("macos"), Some("x86_64")) => "osx-x64",
        (Some("windows"), Some("aarch64")) => "win-arm64",
        (Some("windows"), Some("x86_64")) => "win-x64",
        (Some("linux"), Some("aarch64")) => "linux-arm64",
        (Some("linux"), Some("x86_64")) => "linux-x64",
        other => panic!("unsupported target for bundled C# analyzer: {other:?}"),
    }
}
