fn maybe_publish_csharp_analyzer() {
    if env::var("PROFILE").ok().as_deref() != Some("release") {
        return;
    }

    let Ok(dotnet) = which_dotnet() else {
        println!("cargo:warning=dotnet not found; skipping bundled C# analyzer publish");
        return;
    };

    let manifest_dir = manifest_dir();
    let project = manifest_dir
        .join("tools")
        .join("CodePapr.CSharp.Analyzer")
        .join("CodePapr.CSharp.Analyzer.csproj");
    let output_dir = ui_generated_lsp_resource_dir().join("csharp-analyzer");
    fs::create_dir_all(&output_dir).expect("create csharp analyzer output dir");

    let dotnet_artifacts_dir = manifest_dir.join("target").join("csharp-analyzer-dotnet");
    let dotnet_output_dir = dotnet_artifacts_dir.join("bin");
    let dotnet_intermediate_dir = dotnet_artifacts_dir.join("obj");
    fs::create_dir_all(&dotnet_output_dir).expect("create dotnet analyzer output dir");
    fs::create_dir_all(&dotnet_intermediate_dir).expect("create dotnet analyzer intermediate dir");

    let runtime_identifier = runtime_identifier();
    let status = Command::new(dotnet)
        .arg("publish")
        .arg(&project)
        .arg("-c")
        .arg("Release")
        .arg("-o")
        .arg(&output_dir)
        .arg("-r")
        .arg(runtime_identifier)
        .arg(format!(
            "/p:BaseOutputPath={}",
            msbuild_property_path(&dotnet_output_dir)
        ))
        .arg(format!(
            "/p:BaseIntermediateOutputPath={}",
            msbuild_property_path(&dotnet_intermediate_dir)
        ))
        .arg("--self-contained")
        .arg("true")
        .arg("/p:PublishSingleFile=true")
        .arg("/p:PublishTrimmed=false")
        .arg("/p:DebugType=None")
        .status()
        .expect("run dotnet publish for csharp analyzer");

    if !status.success() {
        panic!("failed to publish bundled C# analyzer");
    }
}

fn ensure_bundled_node_runtime() -> Result<(), String> {
    let install_root = ui_generated_lsp_resource_dir();
    let runtime_dir = install_root.join("node-runtime");
    if managed_node_executable(&runtime_dir).is_some() {
        return Ok(());
    }

    if try_copy_from_managed_cache("node-runtime", &runtime_dir)?
        && managed_node_executable(&runtime_dir).is_some()
    {
        return Ok(());
    }

    let (url, archive_kind) = managed_node_download()?;
    install_archive(&url, archive_kind, &runtime_dir, "node-runtime")?;
    let node = managed_node_executable(&runtime_dir)
        .ok_or_else(|| "bundled node runtime missing executable after install".to_string())?;
    ensure_executable(&node)?;
    Ok(())
}

fn ensure_bundled_node_packages() -> Result<(), String> {
    let install_root = ui_generated_lsp_resource_dir();
    let packages_root = install_root.join("node-packages");
    if !packages_root.join("node_modules").is_dir() {
        let _ = try_copy_from_managed_cache("node-packages", &packages_root)?;
    }

    let node_runtime_root = install_root.join("node-runtime");
    let node = managed_node_executable(&node_runtime_root)
        .ok_or_else(|| "bundled node runtime executable missing".to_string())?;
    let npm_cli = managed_npm_cli(&node_runtime_root)
        .ok_or_else(|| "bundled npm-cli.js not found in managed node runtime".to_string())?;

    fs::create_dir_all(&packages_root)
        .map_err(|err| format!("create bundled node-packages dir: {err}"))?;

    let manifest = json!({
        "name": "codepapr-bundled-lsp-packages",
        "private": true,
        "description": "Bundled desktop LSP packages for CodePapr desktop release",
        "dependencies": bundled_node_package_versions()?,
    });
    let manifest_path = packages_root.join("package.json");
    fs::write(
        &manifest_path,
        serde_json::to_vec_pretty(&manifest)
            .map_err(|err| format!("serialize package.json: {err}"))?,
    )
    .map_err(|err| format!("write bundled node package.json: {err}"))?;

    let status = Command::new(&node)
        .arg(&npm_cli)
        .arg("install")
        .arg("--omit=dev")
        .arg("--no-audit")
        .arg("--no-fund")
        .current_dir(&packages_root)
        .status()
        .map_err(|err| {
            format!(
                "run npm install for bundled node packages with {} {}: {err}",
                node.display(),
                npm_cli.display()
            )
        })?;
    if !status.success() {
        return Err("npm install failed for bundled node packages".to_string());
    }

    for package_name in NODE_LSP_PACKAGES {
        let package_dir = packages_root.join("node_modules").join(package_name);
        if !package_dir.join("package.json").is_file() {
            return Err(format!(
                "missing bundled node package after install: {package_name}"
            ));
        }
    }

    Ok(())
}

fn ensure_bundled_java_support() -> Result<(), String> {
    let install_root = ui_generated_lsp_resource_dir();
    let java_root = install_root.join("java");
    let jdtls_root = java_root.join("jdtls");
    let jre_root = java_root.join("jre");

    if !java_root.exists() {
        println!("cargo:warning=java bundle: probing managed cache copy");
        let _ = try_copy_from_managed_cache("java", &java_root)?;
    }

    if find_jdtls_launcher(&jdtls_root).is_none() {
        println!("cargo:warning=java bundle: downloading/installing jdtls");
        install_archive(JDTLS_DOWNLOAD_URL, ArchiveKind::TarGz, &jdtls_root, "jdtls")?;
        println!("cargo:warning=java bundle: jdtls installed");
    }

    if managed_java_executable(&java_root).is_none() {
        println!("cargo:warning=java bundle: downloading/installing jre");
        let (url, archive_kind) = managed_java_download()?;
        install_archive(&url, archive_kind, &jre_root, "jre")?;
        let java = managed_java_executable(&java_root)
            .ok_or_else(|| "bundled java runtime missing executable after install".to_string())?;
        ensure_executable(&java)?;
        println!("cargo:warning=java bundle: jre installed");
    }

    println!("cargo:warning=java bundle: ready");
    Ok(())
}

