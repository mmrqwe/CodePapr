fn ensure_bundled_rust_analyzer() -> Result<(), String> {
    let install_root = ui_generated_lsp_resource_dir();
    let ra_root = install_root.join("rust-analyzer");
    let output_dir = ra_root.join("bin");
    let output_path = output_dir.join(executable_name("rust-analyzer"));
    if output_path.is_file() {
        ensure_executable(&output_path)?;
        return Ok(());
    }

    if try_copy_from_managed_cache("rust-analyzer", &ra_root)? {
        let copied = ra_root.join("bin").join(executable_name("rust-analyzer"));
        if copied.is_file() {
            ensure_executable(&copied)?;
            return Ok(());
        }
    }

    fs::create_dir_all(&output_dir)
        .map_err(|err| format!("create bundled rust-analyzer dir: {err}"))?;
    let source = ensure_rust_analyzer_on_builder()?;
    fs::copy(&source, &output_path)
        .map_err(|err| format!("copy rust-analyzer into bundled resources: {err}"))?;

    let lib_dir = ra_root.join("lib");
    let _ = fs::create_dir_all(&lib_dir);
    if let Some(parent) = source.parent().and_then(|p| p.parent()) {
        let src_lib = parent.join("lib");
        if src_lib.is_dir() {
            copy_path_recursive(&src_lib, &lib_dir)
                .map_err(|err| format!("copy rust-analyzer libs: {err}"))?;
        }
    }

    ensure_executable(&output_path)?;
    Ok(())
}

fn ensure_rust_analyzer_on_builder() -> Result<PathBuf, String> {
    if let Some(path) = rustup_which_rust_analyzer() {
        return Ok(path);
    }
    if let Some(path) = resolve_command_path("rust-analyzer") {
        return Ok(path);
    }
    if command_exists("rustup") {
        let status = Command::new("rustup")
            .arg("component")
            .arg("add")
            .arg("rust-analyzer")
            .status()
            .map_err(|err| format!("run rustup component add rust-analyzer: {err}"))?;
        if !status.success() {
            return Err("rustup component add rust-analyzer failed".to_string());
        }
        if let Some(path) = rustup_which_rust_analyzer() {
            return Ok(path);
        }
    }
    Err("rust-analyzer not available on builder".to_string())
}

fn rustup_which_rust_analyzer() -> Option<PathBuf> {
    if !command_exists("rustup") {
        return None;
    }
    let output = Command::new("rustup")
        .arg("which")
        .arg("rust-analyzer")
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let path = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim().to_string());
    path.is_file().then_some(path)
}

