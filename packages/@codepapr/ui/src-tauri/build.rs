fn ensure_bundled_typeshed() -> Result<(), String> {
    let install_root = ui_generated_lsp_resource_dir();
    let pyright_dist = install_root
        .join("node-packages")
        .join("node_modules")
        .join("pyright")
        .join("dist");
    let target_stdlib = pyright_dist.join("typeshed-fallback").join("stdlib");
    if target_stdlib.join("builtins.pyi").is_file() {
        return Ok(());
    }

    let url = "https://codeload.github.com/python/typeshed/tar.gz/refs/heads/main";
    let cache_dir = install_root.join("_typeshed");
    let _ = fs::create_dir_all(&cache_dir);
    let archive_path = cache_dir.join("typeshed-main.tar.gz");
    let extract_root = cache_dir.join("extract");

    if !archive_path.is_file() {
        download_to_file(url, &archive_path).map_err(|e| format!("download typeshed: {e}"))?;
        verify_download(url, &archive_path).map_err(|e| format!("verify typeshed: {e}"))?;
    }

    let _ = fs::remove_dir_all(&extract_root);
    fs::create_dir_all(&extract_root)
        .map_err(|err| format!("create typeshed extract dir: {err}"))?;
    extract_archive(&archive_path, ArchiveKind::TarGz, &extract_root)
        .map_err(|e| format!("extract typeshed: {e}"))?;

    let mut stdlib_src = None;
    for entry in std::fs::read_dir(&extract_root).map_err(|e| format!("read extract dir: {e}"))? {
        let path = entry.map_err(|e| format!("read entry: {e}"))?.path();
        if path.is_dir() {
            let stdlib = path.join("stdlib");
            if stdlib.join("builtins.pyi").is_file() {
                stdlib_src = Some(stdlib);
                break;
            }
        }
    }
    let src = stdlib_src
        .ok_or_else(|| format!("stdlib not found in typeshed extract at {:?}", extract_root))?;

    let parent = target_stdlib.parent().ok_or("no parent dir")?;
    fs::create_dir_all(parent).map_err(|e| format!("create target dir: {e}"))?;
    let _ = fs::remove_dir_all(&target_stdlib);
    copy_path_recursive(&src, &target_stdlib).map_err(|e| format!("copy typeshed: {e}"))?;

    if !target_stdlib.join("builtins.pyi").is_file() {
        return Err("typeshed builtins.pyi missing after copy".to_string());
    }
    Ok(())
}

