fn register_build_inputs() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CODEPAPR_SKIP_BUNDLED_LSP_PREPARE");
    println!("cargo:rerun-if-env-changed=CODEPAPR_SKIP_DOWNLOAD_CHECKSUM");
    register_rerun_if_changed(
        &manifest_dir()
            .join("tools")
            .join("CodePapr.CSharp.Analyzer"),
    );

    for path in [
        repo_root().join("package.json"),
        repo_root().join("package-lock.json"),
        ui_generated_lsp_resource_dir().join("bundle-manifest.json"),
    ] {
        if path.exists() {
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}

fn register_rerun_if_changed(path: &Path) {
    if should_skip_csharp_artifact_path(path) {
        return;
    }

    if path.is_file() {
        println!("cargo:rerun-if-changed={}", path.display());
        return;
    }

    let mut children = fs::read_dir(path)
        .unwrap_or_else(|err| panic!("read analyzer input dir {}: {err}", path.display()))
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .collect::<Vec<_>>();
    children.sort();

    for child in children {
        register_rerun_if_changed(&child);
    }
}

fn should_skip_csharp_artifact_path(path: &Path) -> bool {
    path.components()
        .any(|component| matches!(component.as_os_str().to_str(), Some("bin") | Some("obj")))
}

fn ensure_generated_lsp_resource_dir() {
    let resources_dir = ui_generated_lsp_resource_dir();
    fs::create_dir_all(&resources_dir).expect("create generated lsp-tools dir");
    let keep_file = resources_dir.join(".keep");
    if !keep_file.exists() {
        fs::write(&keep_file, b"generated by build.rs\n")
            .expect("create generated lsp-tools placeholder");
    }
}

