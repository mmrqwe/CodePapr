fn remove_jdtls_runtime_temp_files(root: &Path) -> Result<(), String> {
    let jdtls_config = root.join("java").join("jdtls").join("config_win");
    if !jdtls_config.is_dir() {
        return Ok(());
    }

    let mut manager_dirs = Vec::new();
    let mut stack = vec![jdtls_config];
    while let Some(dir) = stack.pop() {
        let entries = match fs::read_dir(&dir) {
            Ok(e) => e,
            Err(_) => continue,
        };
        for entry in entries.filter_map(Result::ok) {
            let path = entry.path();
            if path.is_dir() {
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if name.starts_with(".manager") {
                    manager_dirs.push(path);
                } else {
                    stack.push(path);
                }
            }
        }
    }

    for dir in &manager_dirs {
        let _ = fs::remove_dir_all(dir);
        if dir.exists() {
            let _ = std::process::Command::new("cmd.exe")
                .args(["/c", "rd", "/s", "/q"])
                .arg(dir)
                .status();
        }
    }

    Ok(())
}

fn prune_deep_nested_bundle_paths(root: &Path) -> Result<(), String> {
    #[cfg(target_os = "windows")]
    {
        let test_dir = root
            .join("node-packages")
            .join("node_modules")
            .join("pyright")
            .join("dist")
            .join("typeshed-fallback")
            .join("stdlib")
            .join("@tests");
        if test_dir.exists() {
            let _ = fs::remove_dir_all(&test_dir);
            if test_dir.exists() {
                let _ = std::process::Command::new("cmd.exe")
                    .args(["/c", "rd", "/s", "/q"])
                    .arg(&test_dir)
                    .status();
            }
        }
    }

    let prune_targets: Vec<PathBuf> = vec![];
    for target in &prune_targets {
        if target.exists() {
            let _ = fs::remove_dir_all(target);
            // On Windows, deep paths may survive remove_dir_all; try again
            if target.exists() {
                let _ = std::process::Command::new("cmd.exe")
                    .args(["/c", "rd", "/s", "/q"])
                    .arg(target)
                    .status();
            }
        }
    }

    // Remove unnecessary files from node packages to reduce bundle size and
    // avoid NSIS path-length limits on Windows. LSP servers only need .js files.
    let node_modules = root.join("node-packages").join("node_modules");
    if node_modules.is_dir() {
        prune_node_module_extras(&node_modules)?;
    }

    Ok(())
}

fn prune_node_module_extras(root: &Path) -> Result<(), String> {
    let extensions_to_remove = [".d.ts", ".d.ts.map", ".js.map", ".tsbuildinfo"];
    let files_to_remove = ["CHANGELOG.md", "CHANGES.md", "HISTORY.md"];
    let dirs_to_remove = ["test", "tests", "__tests__", "docs", "examples"];

    let mut stack = vec![root.to_path_buf()];
    let mut dirs_to_prune = Vec::new();
    let mut nested_node_modules = Vec::new();

    while let Some(dir) = stack.pop() {
        let entries = match fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(_) => continue,
        };

        for entry in entries.filter_map(Result::ok) {
            let path = entry.path();
            let metadata = match fs::metadata(&path) {
                Ok(m) => m,
                Err(_) => continue,
            };

            if metadata.is_dir() {
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if dirs_to_remove.contains(&name) {
                    dirs_to_prune.push(path.clone());
                } else if name == "node_modules" && path != *root {
                    // Collect nested node_modules dirs to flatten
                    nested_node_modules.push(path.clone());
                } else {
                    stack.push(path);
                }
            } else if metadata.is_file() {
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
                let should_remove = extensions_to_remove.iter().any(|ext| name.ends_with(ext))
                    || files_to_remove.contains(&name);
                if should_remove {
                    let _ = fs::remove_file(&path);
                }
            }
        }
    }

    for dir in dirs_to_prune {
        let _ = fs::remove_dir_all(&dir);
    }

    // Flatten nested node_modules: move packages from nested node_modules
    // into the top-level node_modules to reduce path depth
    for nested in &nested_node_modules {
        flatten_nested_node_modules(root, nested);
    }

    Ok(())
}

fn flatten_nested_node_modules(top_level: &Path, nested: &Path) {
    let Ok(entries) = fs::read_dir(nested) else {
        return;
    };

    for entry in entries.filter_map(Result::ok) {
        let name = entry.file_name();
        let source = entry.path();
        let destination = top_level.join(&name);

        if destination.exists() {
            // Already exists at top level, skip
            continue;
        }

        // Try to move; if it fails (cross-device or other), try copy
        if fs::rename(&source, &destination).is_err() {
            let _ = copy_path_recursive(&source, &destination);
            let _ = fs::remove_dir_all(&source);
        }
    }

    // Remove the now-empty nested node_modules
    let _ = fs::remove_dir_all(nested);
}

fn normalize_tree_permissions(_root: &Path) -> Result<(), String> {
    #[cfg(unix)]
    {
        normalize_path_permissions(_root)?;
        for path in walk_paths(_root)? {
            normalize_path_permissions(&path)?;
        }
    }

    Ok(())
}

#[cfg(unix)]
fn normalize_path_permissions(_path: &Path) -> Result<(), String> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;

        let metadata = fs::symlink_metadata(_path)
            .map_err(|err| format!("read metadata {}: {err}", _path.display()))?;
        if metadata.file_type().is_symlink() {
            return Ok(());
        }

        let mode = metadata.permissions().mode();
        let normalized_mode = if metadata.is_dir() || mode & 0o111 != 0 {
            0o755
        } else {
            0o644
        };
        if mode != normalized_mode {
            fs::set_permissions(_path, fs::Permissions::from_mode(normalized_mode))
                .map_err(|err| format!("set permissions {}: {err}", _path.display()))?;
        }
    }

    Ok(())
}

fn clear_extended_attributes(_root: &Path) -> Result<(), String> {
    #[cfg(target_os = "macos")]
    {
        let status = Command::new("xattr")
            .arg("-cr")
            .arg(_root)
            .status()
            .map_err(|err| format!("run xattr -cr {}: {err}", _root.display()))?;
        if !status.success() {
            return Err(format!(
                "xattr -cr failed for bundled resources at {}",
                _root.display()
            ));
        }
    }

    Ok(())
}

#[cfg(unix)]
fn walk_paths(root: &Path) -> Result<Vec<PathBuf>, String> {
    let mut paths = Vec::new();
    walk_paths_into(root, &mut paths)?;
    Ok(paths)
}

#[cfg(unix)]
fn walk_paths_into(root: &Path, paths: &mut Vec<PathBuf>) -> Result<(), String> {
    let entries =
        fs::read_dir(root).map_err(|err| format!("read directory {}: {err}", root.display()))?;
    for entry in entries {
        let entry = entry.map_err(|err| format!("read dir entry {}: {err}", root.display()))?;
        let path = entry.path();
        paths.push(path.clone());
        let metadata = fs::symlink_metadata(&path)
            .map_err(|err| format!("read metadata {}: {err}", path.display()))?;
        if metadata.is_dir() && !metadata.file_type().is_symlink() {
            walk_paths_into(&path, paths)?;
        }
    }
    Ok(())
}

// ── Download checksum verification ────────────────────────────────────
// 校验实现与运行时共享 src/download_verification.rs（锁定清单 + 官方校验源）。

/// Verifies a downloaded file via the shared verification module.
///
/// - **Checksum mismatch** → hard error (build fails).
/// - **Checksum fetch failure** → warning (build continues, hash logged).
/// - **No checksum source** → warning with computed SHA-256.
///
/// Set `CODEPAPR_SKIP_DOWNLOAD_CHECKSUM=1` to bypass verification at build
/// time (development only). The runtime path has no such bypass.
fn verify_download(url: &str, file_path: &Path) -> Result<(), String> {
    if env_flag_enabled("CODEPAPR_SKIP_DOWNLOAD_CHECKSUM") {
        println!(
            "cargo:warning=skipping checksum verification (CODEPAPR_SKIP_DOWNLOAD_CHECKSUM=1)"
        );
        return Ok(());
    }

    match download_verification::verify_download(url, file_path) {
        Ok(outcome) => {
            println!(
                "cargo:warning=download verification: {url}: {}",
                outcome.description()
            );
            Ok(())
        }
        Err(err) => Err(format!("checksum verification failed for {url}: {err}")),
    }
}

fn install_archive(
    url: &str,
    archive_kind: ArchiveKind,
    destination: &Path,
    label: &str,
) -> Result<(), String> {
    let parent = destination
        .parent()
        .ok_or_else(|| format!("missing parent dir for {label}"))?;
    fs::create_dir_all(parent).map_err(|err| format!("create parent dir for {label}: {err}"))?;

    let archive_path = parent.join(format!(".{label}.download"));
    let stage_root = parent.join(format!(".{label}.stage"));
    let _ = fs::remove_file(&archive_path);
    let _ = fs::remove_dir_all(&stage_root);

    let install_result = (|| {
        download_to_file(url, &archive_path)?;
        verify_download(url, &archive_path)?;
        fs::create_dir_all(&stage_root).map_err(|err| format!("create staging dir: {err}"))?;
        extract_archive(&archive_path, archive_kind, &stage_root)?;
        let extracted_root = select_extracted_root(&stage_root)?;
        if destination.exists() {
            fs::remove_dir_all(destination).map_err(|err| {
                format!("remove old destination {}: {err}", destination.display())
            })?;
        }
        if extracted_root == stage_root {
            move_path_with_fallback(&stage_root, destination)?;
        } else {
            move_path_with_fallback(&extracted_root, destination)?;
            let _ = fs::remove_dir_all(&stage_root);
        }
        Ok(())
    })();

    let _ = fs::remove_file(&archive_path);
    let _ = fs::remove_dir_all(&stage_root);
    install_result
}

fn download_to_file(url: &str, target: &Path) -> Result<(), String> {
    const DOWNLOAD_RETRIES: usize = 3;

    let mut last_error = String::new();
    for attempt in 1..=DOWNLOAD_RETRIES {
        match download_to_file_once(url, target) {
            Ok(()) => return Ok(()),
            Err(err) => {
                last_error = err;
                if attempt < DOWNLOAD_RETRIES {
                    std::thread::sleep(Duration::from_secs(2));
                }
            }
        }
    }

    Err(format!(
        "download {url} failed after {DOWNLOAD_RETRIES} attempts: {last_error}"
    ))
}

#[cfg(not(windows))]
fn download_to_file_once(url: &str, target: &Path) -> Result<(), String> {
    let client = Client::builder()
        .timeout(DOWNLOAD_TIMEOUT)
        .user_agent("CodePapr-build/0.1")
        .redirect(reqwest::redirect::Policy::limited(10))
        .build()
        .map_err(|err| format!("build download client: {err}"))?;

    let mut response = client
        .get(url)
        .send()
        .map_err(|err| format!("download {url}: {err}"))?;
    if !response.status().is_success() {
        return Err(format!("download {url} returned {}", response.status()));
    }
    if let Some(length) = response.content_length() {
        if length > MAX_DOWNLOAD_BYTES as u64 {
            return Err(format!("download too large for {url}"));
        }
    }

    let mut file = fs::File::create(target)
        .map_err(|err| format!("create download file {}: {err}", target.display()))?;
    let mut downloaded = 0_usize;
    let started_at = Instant::now();
    let mut buffer = [0_u8; 16 * 1024];
    loop {
        if started_at.elapsed() > DOWNLOAD_TIMEOUT {
            return Err(format!(
                "download timed out for {url} after {} seconds",
                DOWNLOAD_TIMEOUT.as_secs()
            ));
        }

        let read = response
            .read(&mut buffer)
            .map_err(|err| format!("read response for {url}: {err}"))?;
        if read == 0 {
            break;
        }
        downloaded += read;
        if downloaded > MAX_DOWNLOAD_BYTES {
            return Err(format!("download too large for {url}"));
        }
        file.write_all(&buffer[..read])
            .map_err(|err| format!("write download file {}: {err}", target.display()))?;
    }

    Ok(())
}

#[cfg(windows)]
fn download_to_file_once(url: &str, target: &Path) -> Result<(), String> {
    download_to_file_with_powershell(url, target)
}

#[cfg(windows)]
fn download_to_file_with_powershell(url: &str, target: &Path) -> Result<(), String> {
    let target_str = target
        .to_string_lossy()
        .replace('\\', "/")
        .replace('"', "\\\"");
    let script = format!(
        "$ProgressPreference='SilentlyContinue'; Invoke-WebRequest -Uri \"{url}\" -OutFile \"{target}\"",
        target = target_str
    );
    let status = Command::new("powershell.exe")
        .arg("-NoProfile")
        .arg("-ExecutionPolicy")
        .arg("Bypass")
        .arg("-Command")
        .arg(script)
        .status()
        .map_err(|err| format!("run Invoke-WebRequest for {url}: {err}"))?;
    if !status.success() {
        return Err(format!("Invoke-WebRequest failed for {url}"));
    }

    let downloaded = fs::metadata(target)
        .map_err(|err| format!("stat download file {}: {err}", target.display()))?
        .len() as usize;
    if downloaded > MAX_DOWNLOAD_BYTES {
        return Err(format!("download too large for {url}"));
    }

    Ok(())
}

fn extract_archive(
    archive_path: &Path,
    archive_kind: ArchiveKind,
    destination: &Path,
) -> Result<(), String> {
    match archive_kind {
        ArchiveKind::TarGz => extract_tar_gz(archive_path, destination),
        ArchiveKind::TarXz => extract_tar_xz(archive_path, destination),
        ArchiveKind::Zip => extract_zip(archive_path, destination),
    }
}

fn extract_tar_gz(archive_path: &Path, destination: &Path) -> Result<(), String> {
    let archive_file = fs::File::open(archive_path)
        .map_err(|err| format!("open tar.gz {}: {err}", archive_path.display()))?;
    let decoder = GzDecoder::new(archive_file);
    Archive::new(decoder)
        .unpack(destination)
        .map_err(|err| format!("extract tar.gz {}: {err}", archive_path.display()))
}

fn extract_tar_xz(archive_path: &Path, destination: &Path) -> Result<(), String> {
    let archive_file = fs::File::open(archive_path)
        .map_err(|err| format!("open tar.xz {}: {err}", archive_path.display()))?;
    let decoder = XzDecoder::new(archive_file);
    Archive::new(decoder)
        .unpack(destination)
        .map_err(|err| format!("extract tar.xz {}: {err}", archive_path.display()))
}

fn extract_zip(archive_path: &Path, destination: &Path) -> Result<(), String> {
    let archive_file = fs::File::open(archive_path)
        .map_err(|err| format!("open zip {}: {err}", archive_path.display()))?;
    let mut archive = ZipArchive::new(archive_file)
        .map_err(|err| format!("read zip {}: {err}", archive_path.display()))?;

    for index in 0..archive.len() {
        let mut entry = archive
            .by_index(index)
            .map_err(|err| format!("read zip entry {index}: {err}"))?;
        let Some(entry_path) = entry.enclosed_name().map(|path| path.to_path_buf()) else {
            continue;
        };
        let target = destination.join(entry_path);
        if entry.is_dir() {
            fs::create_dir_all(&target)
                .map_err(|err| format!("create zip dir {}: {err}", target.display()))?;
            continue;
        }

        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)
                .map_err(|err| format!("create zip parent {}: {err}", parent.display()))?;
        }

        let mut file = fs::File::create(&target)
            .map_err(|err| format!("create zip file {}: {err}", target.display()))?;
        std::io::copy(&mut entry, &mut file)
            .map_err(|err| format!("write zip file {}: {err}", target.display()))?;

        #[cfg(unix)]
        if let Some(mode) = entry.unix_mode() {
            use std::os::unix::fs::PermissionsExt;
            let _ = fs::set_permissions(&target, fs::Permissions::from_mode(mode));
        }
    }

    Ok(())
}

fn select_extracted_root(stage_root: &Path) -> Result<PathBuf, String> {
    let entries = fs::read_dir(stage_root)
        .map_err(|err| format!("read staging dir {}: {err}", stage_root.display()))?
        .filter_map(Result::ok)
        .collect::<Vec<_>>();
    if entries.len() == 1 {
        let path = entries[0].path();
        if path.is_dir() {
            return Ok(path);
        }
    }
    Ok(stage_root.to_path_buf())
}

fn managed_node_download() -> Result<(String, ArchiveKind), String> {
    let (platform, archive_kind) = if target_os() == "macos" {
        ("darwin", ArchiveKind::TarGz)
    } else if target_os() == "linux" {
        ("linux", ArchiveKind::TarXz)
    } else if target_os() == "windows" {
        ("win", ArchiveKind::Zip)
    } else {
        return Err("unsupported target OS for bundled node runtime".to_string());
    };

    let arch = if target_arch() == "aarch64" {
        "arm64"
    } else if target_arch() == "x86_64" {
        "x64"
    } else {
        return Err("unsupported target arch for bundled node runtime".to_string());
    };

    let extension = match archive_kind {
        ArchiveKind::TarGz => "tar.gz",
        ArchiveKind::TarXz => "tar.xz",
        ArchiveKind::Zip => "zip",
    };

    Ok((
        format!(
            "https://nodejs.org/dist/{NODE_RUNTIME_VERSION}/node-{NODE_RUNTIME_VERSION}-{platform}-{arch}.{extension}"
        ),
        archive_kind,
    ))
}

