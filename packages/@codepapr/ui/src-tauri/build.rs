fn flatten_nested_jre_home(root: &Path) -> Result<(), String> {
    let jre_root = root.join("java").join("jre");
    let home_root = jre_root.join("Contents").join("Home");
    if !home_root.is_dir() {
        return Ok(());
    }

    let mut children = fs::read_dir(&home_root)
        .map_err(|err| format!("read nested JRE Home dir {}: {err}", home_root.display()))?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .collect::<Vec<_>>();
    children.sort();

    for child in children {
        let file_name = child
            .file_name()
            .ok_or_else(|| format!("missing file name for {}", child.display()))?;
        let destination = jre_root.join(file_name);
        if destination.exists() {
            continue;
        }
        fs::rename(&child, &destination).map_err(|err| {
            format!(
                "move nested JRE asset {} into {}: {err}",
                child.display(),
                destination.display()
            )
        })?;
    }

    let contents_root = jre_root.join("Contents");
    if contents_root.exists() {
        fs::remove_dir_all(&contents_root).map_err(|err| {
            format!(
                "remove nested JRE bundle structure {}: {err}",
                contents_root.display()
            )
        })?;
    }

    Ok(())
}

